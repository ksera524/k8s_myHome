-- 共用アプリユーザーに DB の所有権を与える。再実行可能。
ALTER DATABASE registry OWNER TO app;
REVOKE CONNECT, TEMPORARY ON DATABASE registry FROM PUBLIC;
GRANT CONNECT ON DATABASE registry TO app;
REVOKE CONNECT ON DATABASE postgres FROM PUBLIC;

